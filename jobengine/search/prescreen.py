"""Deterministic evaluation priority, never a qualification or rejection decision."""

import math
import re
from collections import Counter
from collections.abc import Iterable

from jobengine.grounding import contains_field_quote, keyword_overlap, normalized
from jobengine.models import DiscoveryItem, JobPage, Profile
from jobengine.onboarding.brief import require_confirmed_search_brief

STOP = set(
    "a an and as at be by for from has have in into is it of on or our that the their this to we will with you your staff senior junior entry level intern internship fellow temporary".split()
)


def _terms(text):
    # Small inflection normalization lets reporting/reporter and writing/writer overlap.
    terms = set()
    for word in re.findall(r"[a-z][a-z0-9+#]*", normalized(text)):
        if word in STOP or len(word) < 2:
            continue
        for suffix in ("ing", "ers", "er", "ed", "s"):
            if word.endswith(suffix) and len(word) - len(suffix) >= 4:
                word = word[: -len(suffix)]
                break
        if word.endswith("e") and len(word) > 4:
            word = word[:-1]
        terms.add(word)
    return terms


def _location_signal(profile, text):
    locations = profile.intake.locations if profile.intake else []
    arrangements = profile.intake.work_arrangements if profile.intake else []
    if not profile.intake:
        # Read only the structured wording already generated by JobEngine, not arbitrary prose.
        for constraint in profile.constraints:
            for part in constraint.value.split(";"):
                for prefix in ("On-site and hybrid work must be in:", "Acceptable locations:"):
                    if (
                        constraint.field == "Location / remote / relocation"
                        and part.strip().startswith(prefix)
                    ):
                        locations.extend(
                            x.strip() for x in part.strip()[len(prefix) :].split(",") if x.strip()
                        )
    if not locations:
        return 5.0, "No structured location restriction; geography is neutral."
    marker = re.search(r"^Location:[ \t]*(.*)$", text, re.M)
    location = marker.group(1).strip() if marker else ""
    if not location:
        return 5.0, "Posting location is missing; retain for location verification."
    nyc = {"nyc", "new york city", "new york, ny", "new york, new york"}
    aliases = {normalized(x) for x in locations}
    if aliases & nyc:
        aliases |= nyc
    if any(contains_field_quote(location, alias, 2) for alias in aliases):
        return (
            10.0,
            "Posting location mentions a selected area; arrangement still needs verification.",
        )
    if (
        (not arrangements or "remote" in arrangements)
        and re.search(r"\bremote\b", location, re.I)
        and not re.search(r"\bnot remote\b", location, re.I)
    ):
        return 5.0, "Remote is mentioned; permission to work from the selected area is unverified."
    return (
        0.0,
        "Listed location does not match selected areas; remote/relocation details need verification.",
    )


def prioritize_postings(
    candidates: Iterable[tuple[DiscoveryItem, JobPage]], profile: Profile, *, top_n: int = 10
) -> tuple[list[tuple[DiscoveryItem, JobPage]], list[dict]]:
    """Return selected pairs and the entire scored pool, without I/O or mutation.

    Scores (0-100) prioritize title/roles (45), description/roles (20), interests (20),
    evidence-keyword overlap (5), and location signals (10). Shared corpus vocabulary
    is downweighted with inverse document frequency. No experience/qualification checks,
    relevance threshold, or rejection category applies. Original order breaks ties.
    """
    require_confirmed_search_brief(profile)
    if isinstance(top_n, bool) or not isinstance(top_n, int) or top_n < 0:
        raise ValueError("top_n must be a nonnegative integer.")
    pool = list(candidates)
    documents = []
    for item, page in pool:
        description = page.text.split("\n\nJOB DESCRIPTION\n", 1)[-1]
        documents.append((_terms(item.title), _terms(description), description))
    frequency = Counter(term for title, body, _ in documents for term in title | body)
    weights = {
        term: 1 + math.log((len(pool) + 1) / (count + 1)) for term, count in frequency.items()
    }
    roles = [(role, _terms(role)) for role in profile.target_roles]
    role_terms = set().union(*(terms for _, terms in roles)) if roles else set()
    interests = _terms(profile.interests)

    def weight(terms):
        return sum(weights.get(term, 1 + math.log(len(pool) + 1)) for term in sorted(terms))

    def coverage(query, words):
        return weight(query & words) / weight(query) if query else 0.0

    ranked = []
    for (item, page), (title, body, description) in zip(pool, documents):
        best_title, best_role, title_matches = 0.0, "", set()
        for role, terms in roles:
            overlap = terms & title
            score = len(overlap) / len(title) if title else 0.0
            if score > best_title:
                best_title, best_role, title_matches = score, role, overlap
        role_matches = role_terms & body
        location_points, location_reason = _location_signal(profile, page.text)
        breakdown = {
            "title_roles": round(45 * best_title, 2),
            "description_roles": round(20 * coverage(role_terms, body), 2),
            "description_interests": round(20 * coverage(interests, body), 2),
            "evidence_keywords": round(0.05 * keyword_overlap(profile.evidence, description), 2),
            "location_signal": location_points,
        }
        reasons = [
            f"Closest title role: {best_role}."
            if best_role
            else "No target-role keyword overlap in title; description signals still count.",
            "Description role keywords: " + (", ".join(sorted(role_matches)) or "none"),
            "Description interest keywords: " + (", ".join(sorted(interests & body)) or "none"),
            location_reason,
        ]
        if page.status == "failed":
            reasons.append(
                "Source description failed retrieval/conversion; retained with limited signals."
            )
        ranked.append(
            {
                "item": item,
                "page": page,
                "score": round(sum(breakdown.values()), 2),
                "breakdown": breakdown,
                "matched_title_terms": sorted(title_matches),
                "reasons": reasons,
            }
        )
    ranked.sort(key=lambda row: -row["score"])
    for index, row in enumerate(ranked):
        row.update(
            rank=index + 1,
            status="selected_for_evaluation" if index < top_n else "not_selected_for_batch",
        )
    selected = [(row["item"], row["page"]) for row in ranked[:top_n]]
    return selected, ranked
